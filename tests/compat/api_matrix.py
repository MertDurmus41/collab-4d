"""Which Cinema 4D API the plugin uses, and since which version it exists.   Checked by tests/compat/test_api_matrix.py.

HOW TO READ THIS
  NEWER            API that did not exist in R17: the plugin has a fallback for each, and a test that runs it.
  CHECKED_OLD      looked up in Maxon's Python API docs (2023.2): no "New in version" note newer than R16 on its
                   page. The docs only annotate what is newer than their own baseline (R15/R16), so "no note"
                   means "there since R16 at the latest", i.e. in R17. Constants are not always annotated: the
                   ones that differ between versions are handled in compat.py and were measured on real R19
                   and 2023.
  UNCHECKED        long-standing basic API (points, names, matrices, hierarchy), not looked up one by one.
                   Move a name to CHECKED_OLD after looking it up in the docs.
  NOT_C4D          names the scan picks up that are Python, Windows or our own, not Cinema 4D API.

WHAT THIS DOES NOT SHOW: behaviour. How a real R17 ... R22 or 2024 ... 2026 moves dirty counters or draws is
unknown until someone runs tests/c4d_manual/spike_probe.py there (see ARCHITECTURE.md, "Sürüm uyumluluğu").

Sources: https://developers.maxon.net/docs/py/2023_2/ (class pages), the 2026 SDK examples
(Maxon-Computer/Cinema-4D-Python-API-Examples: most method names appear in them), and real runs on R19.024
and 2023.1.
"""
